-- Money is stored as integer minor units (cents) in BIGINT: never floating point.

CREATE TABLE accounts (
    id             VARCHAR(40)  PRIMARY KEY,
    name           VARCHAR(200) NOT NULL,
    currency       CHAR(3)      NOT NULL,
    -- Funding accounts (a bank, a card network, "the outside world") may go negative; customer accounts may not.
    allow_negative BOOLEAN      NOT NULL DEFAULT FALSE,
    balance        BIGINT       NOT NULL DEFAULT 0,
    -- Sum of open holds. Spendable = balance - pending.
    pending        BIGINT       NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pending_not_negative CHECK (pending >= 0),
    -- The last line of defence: the database itself refuses an overdraft.
    CONSTRAINT no_overdraft CHECK (allow_negative OR balance - pending >= 0)
);

CREATE TABLE transactions (
    id          VARCHAR(40)  PRIMARY KEY,
    kind        VARCHAR(20)  NOT NULL,
    description VARCHAR(500),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Double entry: every transaction's entries sum to zero. Entries are never updated or deleted.
CREATE TABLE entries (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(40) NOT NULL REFERENCES transactions (id),
    account_id     VARCHAR(40) NOT NULL REFERENCES accounts (id),
    amount         BIGINT      NOT NULL,
    balance_after  BIGINT      NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT entry_not_zero CHECK (amount <> 0)
);
CREATE INDEX entries_by_account ON entries (account_id, id);
CREATE INDEX entries_by_transaction ON entries (transaction_id);

CREATE TABLE holds (
    id              VARCHAR(40) PRIMARY KEY,
    account_id      VARCHAR(40) NOT NULL REFERENCES accounts (id),
    destination_id  VARCHAR(40) NOT NULL REFERENCES accounts (id),
    amount          BIGINT      NOT NULL,
    status          VARCHAR(10) NOT NULL,
    captured_amount BIGINT,
    transaction_id  VARCHAR(40) REFERENCES transactions (id),
    expires_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT hold_positive CHECK (amount > 0),
    CONSTRAINT hold_status CHECK (status IN ('PENDING', 'CAPTURED', 'VOIDED', 'EXPIRED'))
);
CREATE INDEX holds_pending_by_expiry ON holds (status, expires_at);

-- A request's Idempotency-Key, a hash of its body, and the response we gave, to replay on retries.
CREATE TABLE idempotency_keys (
    idem_key        VARCHAR(200) PRIMARY KEY,
    request_hash    VARCHAR(64)  NOT NULL,
    response_status INT          NOT NULL,
    response_body   TEXT         NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE webhooks (
    id         VARCHAR(40)  PRIMARY KEY,
    url        VARCHAR(500) NOT NULL,
    secret     VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Transactional outbox: events are written in the same database transaction as the change they
-- describe, so an event exists if and only if the change committed. Delivery happens afterwards.
CREATE TABLE events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type       VARCHAR(50) NOT NULL,
    payload    TEXT        NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE deliveries (
    event_id        BIGINT      NOT NULL REFERENCES events (id),
    webhook_id      VARCHAR(40) NOT NULL REFERENCES webhooks (id),
    attempts        INT         NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    delivered_at    TIMESTAMP WITH TIME ZONE,
    failed          BOOLEAN     NOT NULL DEFAULT FALSE,
    last_error      VARCHAR(500),
    PRIMARY KEY (event_id, webhook_id)
);
CREATE INDEX deliveries_due ON deliveries (delivered_at, failed, next_attempt_at);
